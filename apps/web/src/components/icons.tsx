export type IconName = keyof typeof ICONS;

const FILLED = new Set<IconName>(['stop', 'play', 'zap']);

export function Icon({ name, className = 'h-4 w-4' }: { name: IconName; className?: string }) {
  const C = ICONS[name];
  return <C aria-hidden strokeWidth={2} fill={FILLED.has(name) ? 'currentColor' : 'none'} className={`shrink-0 ${className}`} />;
}
